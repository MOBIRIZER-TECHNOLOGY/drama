/**
 * Permit cleartext HTTP to exactly the hosts a build is pointed at.
 *
 * Android has blocked cleartext traffic by default since API 28, and Expo only relaxes it for the debug
 * variant. A release build aimed at a development machine over the LAN therefore fails every request and
 * every image load, with nothing in the app to say why — the socket is refused below the fetch layer.
 *
 * The blunt fix is `android:usesCleartextTraffic="true"`, which would ship in the store build and quietly
 * remove the protection from production too. This instead writes a network security config naming only the
 * hosts handed to it, and only the ones actually reached over http. Point a build at https and the plugin
 * adds nothing at all: no manifest attribute, no config file.
 */
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

const RESOURCE = "network_security_config";

/** Hostnames from `urls` that are reached over plain http. https and malformed entries are dropped. */
function cleartextHosts(urls) {
  const hosts = new Set();
  for (const url of urls) {
    if (!url) continue;
    try {
      const { protocol, hostname } = new URL(url);
      if (protocol === "http:" && hostname) hosts.add(hostname);
    } catch {
      // A value that is not a URL is not a host to open up.
    }
  }
  return [...hosts].sort();
}

function xml(hosts) {
  const domains = hosts.map((h) => `        <domain includeSubdomains="false">${h}</domain>`).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-cleartext-hosts.js. Do not edit: prebuild overwrites it. -->
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
${domains}
    </domain-config>
</network-security-config>
`;
}

module.exports = function withCleartextHosts(config, { urls = [] } = {}) {
  const hosts = cleartextHosts(urls);
  if (hosts.length === 0) return config;

  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, `${RESOURCE}.xml`), xml(hosts), "utf8");
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$["android:networkSecurityConfig"] = `@xml/${RESOURCE}`;
    return cfg;
  });
};

module.exports.cleartextHosts = cleartextHosts;
