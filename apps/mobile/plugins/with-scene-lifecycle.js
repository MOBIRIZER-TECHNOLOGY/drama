/**
 * Adopt the UIKit scene lifecycle on iOS.
 *
 * Apps linked against the iOS 27 SDK must adopt UIScene: UIKit refuses to launch one that still drives its
 * window from the application delegate, and it says so only in the device log — the app is killed before a
 * line of JavaScript runs, and to a viewer it simply never opens. React Native's app delegate template (0.86)
 * still creates the window in `didFinishLaunching`, so every build of this app from Xcode 27 dies that way on
 * the simulator and on a phone.
 *
 * This plugin moves window creation into a scene delegate and leaves everything else where React Native and
 * Expo expect it. The delegate hands the window to the React Native factory the app delegate already built,
 * and forwards the URL and user-activity callbacks that UIKit now delivers to the scene back to the app
 * delegate, so deep links, universal links and Google's sign-in redirect keep reaching the same code.
 *
 * Applied at prebuild, because `ios/` is generated and not committed: Info.plist gains the scene manifest,
 * SceneDelegate.swift is written beside AppDelegate.swift and added to the target, and the template's
 * window lines in AppDelegate.swift are replaced with a record of the launch options for the scene to use.
 */
const { IOSConfig, withDangerousMod, withInfoPlist, withXcodeProject } = require("expo/config-plugins");
const fs = require("fs");
const path = require("path");

const SCENE_DELEGATE = `import UIKit
import React

// Generated by plugins/with-scene-lifecycle.js. Do not edit: prebuild overwrites it.
//
// The window is created here, attached to the scene UIKit hands us, rather than in the app delegate: that is
// the whole of what the iOS 27 SDK requires. React Native itself is still started by the factory the app
// delegate built, and every URL or activity the scene receives is passed back to the app delegate, whose
// handlers are what React Native's linking and Expo's modules subscribe to.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(_ scene: UIScene, willConnectTo session: UISceneSession, options connectionOptions: UIScene.ConnectionOptions) {
    guard let windowScene = scene as? UIWindowScene,
      let appDelegate = UIApplication.shared.delegate as? AppDelegate,
      let factory = appDelegate.reactNativeFactory
    else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: appDelegate.launchOptions)
    window.makeKeyAndVisible()

    // A link that launched the app arrives with the scene, not with didFinishLaunching.
    for context in connectionOptions.urlContexts {
      _ = appDelegate.application(UIApplication.shared, open: context.url, options: [:])
    }
    for activity in connectionOptions.userActivities {
      _ = appDelegate.application(UIApplication.shared, continue: activity, restorationHandler: { _ in })
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let appDelegate = UIApplication.shared.delegate as? AppDelegate else { return }
    for context in URLContexts {
      _ = appDelegate.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    guard let appDelegate = UIApplication.shared.delegate as? AppDelegate else { return }
    _ = appDelegate.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

/** The template's window block, which the scene delegate replaces. Matched loosely: whitespace varies. */
const WINDOW_BLOCK = /#if os\(iOS\) \|\| os\(tvOS\)\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*factory\.startReactNative\(\s*withModuleName: "main",\s*in: window,\s*launchOptions: launchOptions\)\s*#endif/;

function patchAppDelegate(source) {
  if (source.includes("var launchOptions:")) return source; // already patched
  if (!WINDOW_BLOCK.test(source)) {
    throw new Error(
      "with-scene-lifecycle: AppDelegate.swift no longer matches the React Native template this plugin patches; update the plugin.",
    );
  }
  let out = source.replace(
    WINDOW_BLOCK,
    [
      "    // The window is created by SceneDelegate when UIKit connects the scene (see plugins/with-scene-lifecycle.js);",
      "    // the launch options are kept for it, because they are only handed to this method.",
      "    self.launchOptions = launchOptions",
    ].join("\n"),
  );
  out = out.replace(
    "  var window: UIWindow?\n",
    "  var window: UIWindow?\n  var launchOptions: [UIApplication.LaunchOptionsKey: Any]?\n",
  );
  return out;
}

module.exports = function withSceneLifecycle(config) {
  config = withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: "Default Configuration",
            UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
          },
        ],
      },
    };
    return cfg;
  });

  config = withDangerousMod(config, [
    "ios",
    async (cfg) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
      const dir = path.join(cfg.modRequest.platformProjectRoot, projectName);
      await fs.promises.writeFile(path.join(dir, "SceneDelegate.swift"), SCENE_DELEGATE, "utf8");
      const appDelegatePath = path.join(dir, "AppDelegate.swift");
      const source = await fs.promises.readFile(appDelegatePath, "utf8");
      await fs.promises.writeFile(appDelegatePath, patchAppDelegate(source), "utf8");
      return cfg;
    },
  ]);

  return withXcodeProject(config, (cfg) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const filepath = `${projectName}/SceneDelegate.swift`;
    if (!cfg.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: cfg.modResults,
      });
    }
    return cfg;
  });
};

module.exports.patchAppDelegate = patchAppDelegate;
