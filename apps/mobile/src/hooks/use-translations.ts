export function useT() {
  const { messages } = useConfig();
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let s = messages[key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    [messages],
  );
}
